class CAIPDF(FPDF):
    """Pre-configured FPDF subclass with DejaVu Sans for full Unicode support."""

    def __init__(self) -> None:
        super().__init__("P", "mm", "A4")
        self.set_auto_page_break(auto=True, margin=18)
        font_path = _ensure_font()
        if font_path:
            self.add_font("DejaVu", "", font_path, uni=True)
            self.add_font("DejaVu", "B", font_path, uni=True)
            self._font_ok = True
        else:
            self._font_ok = False

    def header(self) -> None:
        if self.page_no() == 1:
            return  # Title handled on first page
        self._safe_font("B", 8)
        self.set_text_color(100, 100, 100)
        self._safe_cell(0, 5, "CAI  |  Tax Report", align="L")
        self.ln(6)

    def footer(self) -> None:
        self.set_y(-15)
        self._safe_font("", 7)
        self.set_text_color(140, 140, 140)
        self._safe_cell(0, 10, f"Page {self.page_no()}/{{nb}} | Generated by CAI | Powered by Gemma 4", align="C")

    def _safe_font(self, style: str = "", size: float = 10) -> None:
        if self._font_ok:
            self.set_font("DejaVu", style, size)
        else:
            self.set_font("Helvetica", style, size)

    def _safe_cell(self, w: float, h: float = 6, txt: str = "", **kwargs: Any) -> None:
        """Write text that won't crash on Unicode — substitute if needed."""
        if self._font_ok:
            self.cell(w, h, txt, **kwargs)
        else:
            safe = txt.encode("ascii", errors="replace").decode("ascii")
            self.cell(w, h, safe, **kwargs)

    def section_title(self, title: str) -> None:
        self.ln(4)
        self._safe_font("B", 13)
        self.set_text_color(15, 23, 42)
        self._safe_cell(0, 8, title)
        self.ln(9)
        self.set_draw_color(245, 158, 11)  # amber/gold accent line
        self.set_line_width(0.4)
        self.line(self.l_margin, self.get_y(), self.w - self.r_margin, self.get_y())
        self.ln(4)

    def key_value_row(self, key: str, value: str, indent: float = 10) -> None:
        self._safe_font("", 10)
        self.set_text_color(60, 60, 60)
        self._safe_cell(indent)
        self._safe_cell(55, 6, key + ":")
        self.set_text_color(15, 23, 42)
        self._safe_font("B", 10)
        self._safe_cell(0, 6, value)
        self.ln(6)

    def deduction_table(self, deductions: List[Dict[str, Any]]) -> None:
        headers = ["Section", "Category", "Eligible", "Claimed", "Remaining", "Status", "Confidence"]
        col_widths = [22, 24, 26, 26, 26, 28, 26]
        total_w = sum(col_widths)

        # Header row
        self._safe_font("B", 8)
        self.set_fill_color(15, 23, 42)
        self.set_text_color(255, 255, 255)
        for header, cw in zip(headers, col_widths):
            self._safe_cell(cw, 7, header, border=1, fill=True, align="C")
        self.ln()

        # Data rows
        for i, item in enumerate(deductions):
            if i % 2 == 0:
                self.set_fill_color(248, 250, 252)
            else:
                self.set_fill_color(255, 255, 255)

            status = str(item.get("status", "-"))
            confidence = str(item.get("confidence", "-"))

            # Color-code confidence
            if confidence == "high":
                self.set_text_color(22, 163, 74)
            elif confidence == "low":
                self.set_text_color(220, 38, 38)
            else:
                self.set_text_color(202, 138, 4)

            row_data = [
                str(item.get("section", "-")),
                str(item.get("category", "-"))[:14],
                format_inr(item.get("eligible_amount", 0)),
                format_inr(item.get("claimed_amount", 0)),
                format_inr(item.get("remaining_opportunity", 0)),
                status.replace("_", " ").title(),
                confidence.title(),
            ]

            self._safe_font("", 7)
            for val, cw in zip(row_data, col_widths):
                self._safe_cell(cw, 6, val, border=1, fill=True, align="C")
            self.ln()

        self.set_text_color(15, 23, 42)

    def tax_comparison_table(self, tax: Dict[str, Any]) -> None:
        old = tax.get("old_regime", {})
        new = tax.get("new_regime", {})
        rows = [
            ("Gross Income", old.get("gross_income", 0), new.get("gross_income", 0)),
            ("Standard Deduction", -old.get("standard_deduction", 0), -new.get("standard_deduction", 0)),
            ("Total Deductions", -old.get("total_deductions", 0), -new.get("total_deductions", 0)),
            ("Taxable Income", old.get("taxable_income", 0), new.get("taxable_income", 0)),
            ("Tax Before Rebate", old.get("tax_before_rebate", 0), new.get("tax_before_rebate", 0)),
            ("Rebate", -old.get("rebate", 0), -new.get("rebate", 0)),
            ("Cess", old.get("cess", 0), new.get("cess", 0)),
            ("Final Tax", old.get("final_tax", 0), new.get("final_tax", 0)),
        ]

        headers = ["Breakdown", "Old Regime", "New Regime"]
        col_widths = [50, 45, 45]

        self._safe_font("B", 9)
        self.set_fill_color(15, 23, 42)
        self.set_text_color(255, 255, 255)
        for header, cw in zip(headers, col_widths):
            self._safe_cell(cw, 7, header, border=1, fill=True, align="C")
        self.ln()

        for i, (label, old_val, new_val) in enumerate(rows):
            is_final = label == "Final Tax"
            if i % 2 == 0:
                self.set_fill_color(248, 250, 252)
            else:
                self.set_fill_color(255, 255, 255)

            col1_color = (22, 163, 74) if (is_final and old_val < new_val) else (15, 23, 42)
            col2_color = (22, 163, 74) if (is_final and new_val < old_val) else (15, 23, 42)

            self._safe_font("B", 8) if is_final else self._safe_font("", 8)
            self.set_text_color(15, 23, 42)
            self._safe_cell(col_widths[0], 6, label, border=1, fill=True)

            self.set_text_color(*col1_color)
            self._safe_cell(col_widths[1], 6, format_inr(old_val), border=1, fill=True, align="R")

            self.set_text_color(*col2_color)
            self._safe_cell(col_widths[2], 6, format_inr(new_val), border=1, fill=True, align="R")
            self.ln()

        self.set_text_color(15, 23, 42)

        # Recommendation footer
        self.ln(3)
        self._safe_font("B", 10)
        rec = str(tax.get("recommended_regime", "old")).title()
        savings = format_inr(tax.get("savings", 0))
        self._safe_cell(0, 7, f"Recommended: {rec} Regime | You save {savings}")

    def scenario_cards(self, scenarios: List[Dict[str, Any]]) -> None:
        for idx, s in enumerate(scenarios, start=1):
            self._safe_font("B", 10)
            self.set_text_color(15, 23, 42)
            self._safe_cell(0, 6, f"Scenario {idx}: {s.get('title', '-')}")
            self.ln(6)

            self._safe_font("", 9)
            self.set_text_color(80, 80, 80)
            details = [
                ("Action", s.get("action", "-")),
                ("Section", s.get("section", "-")),
                ("Additional Amount", format_inr(s.get("additional_amount", 0))),
                ("Tax Impact", format_inr(s.get("estimated_tax_impact", 0))),
                ("Net Savings", format_inr(s.get("net_savings", 0))),
                ("Confidence", s.get("confidence", "-").title()),
            ]
            for key, val in details:
                self._safe_cell(8)
                self._safe_font("B", 9)
                self._safe_cell(40, 5, key + ":")
                self._safe_font("", 9)
                self._safe_cell(0, 5, str(val))
                self.ln(5)
            self.ln(3)


def generate_pdf_report(
    profile: Dict[str, Any],
    deductions: List[Dict[str, Any]],
    tax: Dict[str, Any],
    scenarios: List[Dict[str, Any]],
    risk: Dict[str, Any],
    missing_evidence: List[Dict[str, Any]],
) -> bytes:
    """Generate a complete, Unicode-safe PDF tax report."""
    user_name = profile.get("name") or "Taxpayer"
    today = datetime.now().strftime(DATE_FORMAT)

    pdf = CAIPDF()
    pdf.alias_nb_pages()
    pdf.add_page()

    # ── Cover / Title ──────────────────────────────────────────────────
    pdf.ln(8)
    pdf._safe_font("B", 22)
    pdf.set_text_color(15, 23, 42)
    pdf._safe_cell(0, 10, "CAI", align="C")
    pdf.ln(12)
    pdf._safe_font("", 12)
    pdf.set_text_color(245, 158, 11)
    pdf._safe_cell(0, 7, "Tax Report", align="C")
    pdf.ln(10)
    pdf.set_draw_color(245, 158, 11)
    pdf.set_line_width(0.6)
    y = pdf.get_y()
    pdf.line(60, y, pdf.w - 60, y)
    pdf.ln(10)

    pdf._safe_font("", 10)
    pdf.set_text_color(80, 80, 80)
    pdf._safe_cell(0, 6, f"Prepared for: {user_name}", align="C")
    pdf.ln(6)
    pdf._safe_cell(0, 6, f"Date: {today}", align="C")
    pdf.ln(6)
    pdf._safe_cell(0, 6, f"City: {profile.get('city', 'Not specified')}", align="C")
    pdf.ln(12)

    # ── 1) Financial Profile ───────────────────────────────────────────
    pdf.section_title("1. Financial Profile")
    pdf.key_value_row("Annual Income", format_inr(profile.get("annual_income", 0)))
    pdf.key_value_row("Basic Salary", format_inr(profile.get("basic_salary", 0)))
    pdf.key_value_row("HRA Received", format_inr(profile.get("hra_received", 0)))
    pdf.key_value_row("Rent Paid", format_inr(profile.get("rent_paid", 0)))
    pdf.key_value_row("Savings Interest", format_inr(profile.get("savings_interest", 0)))
    pdf.key_value_row("Education Loan Interest", format_inr(profile.get("education_loan_interest", 0)))
    pdf.key_value_row("Donations (80G)", format_inr(profile.get("donations", 0)))

    # ── 2) Deduction Discovery ─────────────────────────────────────────
    pdf.section_title("2. Deduction Discovery")
    if deductions:
        pdf.deduction_table(deductions)
    else:
        pdf._safe_font("", 10)
        pdf.set_text_color(120, 120, 120)
        pdf._safe_cell(0, 6, "No deductions analysed yet.")

    # ── 3) Missing Evidence ────────────────────────────────────────────
    pdf.section_title("3. Missing Evidence Checklist")
    if missing_evidence:
        for row in missing_evidence:
            pdf._safe_font("", 9)
            pdf.set_text_color(180, 83, 9)
            status_label = str(row.get("status", "-")).replace("_", " ").title()
            bullet = f"[{status_label}] {row.get('item', '-')}: {row.get('details', '-')}"
            pdf._safe_cell(10)
            pdf._safe_cell(0, 5, bullet)
            pdf.ln(5)
    else:
        pdf._safe_font("", 10)
        pdf.set_text_color(22, 163, 74)
        pdf._safe_cell(10)
        pdf._safe_cell(0, 6, "No missing evidence flagged.")

    # ── 4) Tax Computation ─────────────────────────────────────────────
    pdf.section_title("4. Tax Computation — Old vs New Regime")
    pdf.tax_comparison_table(tax)

    # ── 5) What-If Scenarios ───────────────────────────────────────────
    pdf.section_title("5. Tax Planning Scenarios")
    if scenarios:
        pdf.scenario_cards(scenarios)
    else:
        pdf._safe_font("", 10)
        pdf.set_text_color(120, 120, 120)
        pdf._safe_cell(0, 6, "No scenarios generated yet.")

    # ── 6) Audit Risk ──────────────────────────────────────────────────
    pdf.section_title("6. Audit Risk Assessment")
    pdf._safe_font("B", 11)
    risk_level = str(risk.get("risk_level", "Unknown"))
    risk_score = risk.get("risk_score", 0)

    if risk_level.lower() == "low":
        pdf.set_text_color(22, 163, 74)
    elif risk_level.lower() == "medium":
        pdf.set_text_color(202, 138, 4)
    else:
        pdf.set_text_color(220, 38, 38)

    pdf._safe_cell(0, 7, f"Risk Level: {risk_level} ({risk_score}/100)")
    pdf.ln(7)
    pdf._safe_font("", 9)
    pdf.set_text_color(80, 80, 80)
    pdf._safe_cell(0, 5, str(risk.get("why", "")))
    pdf.ln(7)

    pdf._safe_font("B", 10)
    pdf.set_text_color(15, 23, 42)
    pdf._safe_cell(0, 6, "Red Flags:")
    pdf.ln(6)
    for flag in risk.get("red_flags", []) or []:
        pdf._safe_font("", 9)
        pdf.set_text_color(80, 80, 80)
        pdf._safe_cell(8)
        pdf._safe_cell(0, 5, "  •  " + str(flag))
        pdf.ln(5)

    pdf.ln(3)
    pdf._safe_font("B", 10)
    pdf.set_text_color(15, 23, 42)
    pdf._safe_cell(0, 6, "Mitigation Steps:")
    pdf.ln(6)
    for step in risk.get("mitigation_steps", []) or []:
        pdf._safe_font("", 9)
        pdf.set_text_color(80, 80, 80)
        pdf._safe_cell(8)
        pdf._safe_cell(0, 5, "  -  " + str(step))
        pdf.ln(5)

    return bytes(pdf.output())


def get_download_button(content: bytes, filename: str, label: str, mime: str) -> None:
    """Render a Streamlit download button."""
    st.download_button(
        label=label,
        data=content,
        file_name=filename,
        mime=mime,
        use_container_width=True,
    )
