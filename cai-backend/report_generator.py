from config import DATE_FORMAT, format_inr

# ═══════════════════════════════════════════════════════════════════════════
# Unicode-ready font bootstrap (self-healing)
# ═══════════════════════════════════════════════════════════════════════════
_FONT_DIR = os.path.join(tempfile.gettempdir(), "cai_fonts")
_FONT_PATH = os.path.join(_FONT_DIR, "DejaVuSans.ttf")
_FONT_URL = (
    "https://github.com/dejavu-fonts/dejavu-fonts/raw/master/ttf/DejaVuSans.ttf"
)


def _ensure_font() -> str:
    """Download DejaVuSans.ttf if missing. Returns path to TTF file."""
    os.makedirs(_FONT_DIR, exist_ok=True)
    if not os.path.exists(_FONT_PATH):
        try:
            urllib.request.urlretrieve(_FONT_URL, _FONT_PATH)
        except Exception:
            # If download fails, return empty string — caller should handle gracefully
            return ""
    return _FONT_PATH if os.path.getsize(_FONT_PATH) > 1000 else ""


# ═══════════════════════════════════════════════════════════════════════════
# PDF Generation
